#!/usr/bin/env python3
"""Turns suite.cfg into src/suite_data.h so the whole test list is compiled into the exe.
Usage: python tools/gen_suite.py        (run from anywhere; paths are relative to this file)
The text is emitted as several string literals because MSVC limits one literal to ~16 KB."""
import os

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
data = open(os.path.join(root, "suite.cfg"), "rb").read().decode("utf-8")
assert all(ord(c) < 128 for c in data), "suite.cfg must be plain ASCII"

parts, cur = [], ""
for line in data.splitlines(keepends=True):
    if len(cur) + len(line) > 6000:
        parts.append(cur)
        cur = ""
    cur += line
if cur:
    parts.append(cur)


def lit(text):
    out = []
    for ln in text.splitlines(keepends=True):
        e = ln.replace("\\", "\\\\").replace('"', '\\"').replace("\r", "").replace("\n", "\\n")
        out.append('    "' + e + '"')
    return "\n".join(out)


with open(os.path.join(root, "src", "suite_data.h"), "w", newline="\n") as f:
    f.write("// GENERATED by tools/gen_suite.py from suite.cfg - do not edit by hand.\n#pragma once\n")
    f.write("static const int SUITE_CFG_NPARTS = %d;\nstatic const char* const SUITE_CFG_PARTS[%d] = {\n" % (len(parts), len(parts)))
    f.write(",\n".join(lit(p) for p in parts))
    f.write("\n};\n")
print("suite.cfg ->", "src/suite_data.h", "(%d bytes, %d parts)" % (len(data), len(parts)))
