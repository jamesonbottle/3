#!/usr/bin/env python3
"""Turns suite.cfg into src/suite_data.h so the whole test list is compiled into the exe.
Usage: python tools/gen_suite.py          (run from anywhere; paths are relative to this file) writes src/suite_data.h
       python tools/gen_suite.py --check  writes nothing; exits 1 if src/suite_data.h differs from what suite.cfg generates
The text is emitted as several string literals because MSVC limits one literal to ~16 KB."""
import os
import sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out_path = os.path.join(root, "src", "suite_data.h")

args = sys.argv[1:]
if args not in ([], ["--check"]):
    sys.stderr.write("usage: gen_suite.py [--check]\n")
    sys.exit(2)
check_only = args == ["--check"]

data = open(os.path.join(root, "suite.cfg"), "rb").read().decode("utf-8")
assert all(ord(c) < 128 for c in data), "suite.cfg must be plain ASCII"

parts, cur = [], ""
for line in data.splitlines(keepends=True):
    if len(cur) + len(line) > 6000:
        parts.append(cur)
        cur = ""
    cur += line
if cur:
    parts.append(cur)


def lit(text):
    out = []
    for ln in text.splitlines(keepends=True):
        e = ln.replace("\\", "\\\\").replace('"', '\\"').replace("\r", "").replace("\n", "\\n")
        out.append('    "' + e + '"')
    return "\n".join(out)


# the whole generated file, in memory (always "\n" line endings, like the committed file)
header = "// GENERATED by tools/gen_suite.py from suite.cfg - do not edit by hand.\n#pragma once\n"
header += "static const int SUITE_CFG_NPARTS = %d;\nstatic const char* const SUITE_CFG_PARTS[%d] = {\n" % (len(parts), len(parts))
generated = header + ",\n".join(lit(p) for p in parts) + "\n};\n"

if check_only:
    try:
        current = open(out_path, "rb").read()
    except OSError:
        current = None
    if current != generated.encode("ascii"):
        sys.stderr.write("src/suite_data.h is out of date with suite.cfg - run python tools/gen_suite.py\n")
        sys.exit(1)
    print("src/suite_data.h is up to date with suite.cfg")
    sys.exit(0)

with open(out_path, "w", newline="\n") as f:
    f.write(generated)
print("suite.cfg ->", "src/suite_data.h", "(%d bytes, %d parts)" % (len(data), len(parts)))
